#!/usr/bin/env python3
"""Generate a C++ header from the reviewed, built userscript, without network I/O."""
from pathlib import Path
import hashlib
root = Path(__file__).resolve().parents[2]
source = root / 'dearrow/tizentube/dist/userScript.js'
script = source.read_text()
delimiter = 'TIZEN_DEARROW'
if ')' + delimiter + '"' in script:
    raise SystemExit('Raw string delimiter collision')
path = root / 'dearrow/generated/userscript.h'
path.parent.mkdir(parents=True, exist_ok=True)
path.write_text('// Generated by dearrow/tools/embed-userscript.py; do not edit.\n'
    '// GPL-3.0-only userscript; see dearrow/tizentube/LICENSE.\n'
    '// SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
    '#ifndef TIZENDEARROW_GENERATED_USERSCRIPT_H_\n#define TIZENDEARROW_GENERATED_USERSCRIPT_H_\n'
    'inline constexpr char kTizenDeArrowScript[] = R"' + delimiter + '(' + script + ')' + delimiter + '";\n#endif\n')
print(path.relative_to(root), 'sha256', hashlib.sha256(source.read_bytes()).hexdigest())
